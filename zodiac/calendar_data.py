def leap_month(year: int) -> int:
    """Return the leap month number for ``year`` (0 when there is none)."""
    return LUNAR_INFO[year - LUNAR_MIN_YEAR] & 0xF


def leap_days(year: int) -> int:
    """Return the number of days in ``year``'s leap month (0 when absent)."""
    if leap_month(year) == 0:
        return 0
    return 30 if (LUNAR_INFO[year - LUNAR_MIN_YEAR] & 0x10000) else 29


def month_days(year: int, month: int) -> int:
    """Return the number of days in the regular ``month`` of ``year``."""
    if LUNAR_INFO[year - LUNAR_MIN_YEAR] & (0x10000 >> month):
        return 30
    return 29


def year_months(year: int) -> List[Tuple[int, bool, int]]:
    """Return ``(month, is_leap, days)`` tuples in chronological order."""
    months: List[Tuple[int, bool, int]] = []
    leap = leap_month(year)
    for month in range(1, 13):
        months.append((month, False, month_days(year, month)))
        if leap == month:
            months.append((month, True, leap_days(year)))
    return months


def year_days(year: int) -> int:
    """Return the total number of days in lunar ``year``."""
    return sum(days for _, _, days in year_months(year))